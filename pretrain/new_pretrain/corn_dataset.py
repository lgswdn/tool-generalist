"""CORN contact dataset for new_pretrain.

Samples are generated by ~/corn/pkm/scripts/pretrain/gen_col/gen_col.py and
stored as one pickle per scene.  Each sample contains a world-frame object cloud
and per-object-point contact flags.  Tool point clouds are reconstructed from
the same COACD tool assets used during generation.
"""

from __future__ import annotations

import pickle
import random
from pathlib import Path
from typing import List, Tuple

import torch
from torch.utils.data import Dataset


DEFAULT_TOOL_ROOT = "/home/galbot/tool/eef/meshdata_adjusted"


def _quat_xyzw_to_matrix(q: torch.Tensor) -> torch.Tensor:
    q = q / q.norm().clamp_min(1e-12)
    qx, qy, qz, qw = q.unbind(-1)

    tx = 2.0 * qx
    ty = 2.0 * qy
    tz = 2.0 * qz
    twx = tx * qw
    twy = ty * qw
    twz = tz * qw
    txx = tx * qx
    txy = ty * qx
    txz = tz * qx
    tyy = ty * qy
    tyz = tz * qy
    tzz = tz * qz

    rot = torch.empty(3, 3, dtype=q.dtype, device=q.device)
    rot[0, 0] = 1.0 - (tyy + tzz)
    rot[0, 1] = txy - twz
    rot[0, 2] = txz + twy
    rot[1, 0] = txy + twz
    rot[1, 1] = 1.0 - (txx + tzz)
    rot[1, 2] = tyz - twx
    rot[2, 0] = txz - twy
    rot[2, 1] = tyz + twx
    rot[2, 2] = 1.0 - (txx + tyy)
    return rot


def _apply_pose(points: torch.Tensor, pose: torch.Tensor) -> torch.Tensor:
    rot = _quat_xyzw_to_matrix(pose[3:7])
    return points @ rot.T + pose[:3]


def _scene_to_meshes(scene):
    meshes = []
    for node_name in scene.graph.nodes_geometry:
        transform, geometry_name = scene.graph[node_name]
        mesh = scene.geometry[geometry_name].copy()
        mesh.apply_transform(transform)
        if len(mesh.vertices) > 0:
            meshes.append(mesh)
    return meshes


def _load_tool_mesh(tool_dir: Path):
    import trimesh

    coacd_dir = tool_dir / "coacd"
    mesh_path = coacd_dir / "decomposed.obj"
    if mesh_path.is_file():
        loaded = trimesh.load_mesh(mesh_path, force="mesh")
        if isinstance(loaded, trimesh.Scene):
            meshes = _scene_to_meshes(loaded)
            if meshes:
                return trimesh.util.concatenate(meshes)
        return loaded

    pieces = sorted(coacd_dir.glob("coacd_convex_piece_*.obj"))
    if not pieces:
        raise FileNotFoundError(f"No tool mesh found under {coacd_dir}")
    meshes = [trimesh.load_mesh(str(p), force="mesh") for p in pieces]
    return trimesh.util.concatenate(meshes)


def _sample_mesh_points(mesh, num_pts: int) -> torch.Tensor:
    import numpy as np

    if len(mesh.faces) > 0:
        pts = mesh.sample(num_pts)
    else:
        verts = np.asarray(mesh.vertices)
        if len(verts) == 0:
            raise ValueError("Tool mesh has no vertices")
        if len(verts) >= num_pts:
            idx = np.linspace(0, len(verts) - 1, num_pts).astype(np.int64)
        else:
            idx = np.arange(num_pts) % len(verts)
        pts = verts[idx]
    return torch.as_tensor(pts, dtype=torch.float32)


class CornContactDataset(Dataset):
    """Dataset for object-patch contact prediction.

    Returns:
      - tool_pc:          (N, 3) tool point cloud in world frame
      - obj_pc:           (N, 3) object point cloud in world frame
      - obj_contact_flag: (N,)   per-object-point binary contact labels
    """

    def __init__(
        self,
        pkl_files: List[str],
        tool_root: str = DEFAULT_TOOL_ROOT,
        num_pts: int = 512,
        augment: bool = True,
    ):
        self.paths = [str(p) for p in pkl_files if Path(p).is_file()]
        self.tool_root = Path(tool_root)
        self.num_pts = int(num_pts)
        self.augment = augment
        self._tool_cache: dict[tuple[str, float], torch.Tensor] = {}
        self._skipped_files = [str(p) for p in pkl_files if not Path(p).is_file()]

    def __len__(self) -> int:
        return len(self.paths)

    def get_skipped_files(self) -> List[str]:
        return self._skipped_files

    def _load_tool_cloud(self, tool_key: str, tool_scale: float) -> torch.Tensor:
        cache_key = (tool_key, float(tool_scale))
        cached = self._tool_cache.get(cache_key)
        if cached is not None:
            return cached

        mesh = _load_tool_mesh(self.tool_root / tool_key)
        if tool_scale != 1.0:
            mesh.apply_scale(float(tool_scale))
        cloud = _sample_mesh_points(mesh, self.num_pts).float()
        self._tool_cache[cache_key] = cloud
        return cloud

    def _sample_indices(self, n: int) -> torch.Tensor:
        if n == self.num_pts:
            return torch.arange(n, dtype=torch.long)
        if n > self.num_pts:
            if self.augment:
                return torch.randperm(n)[: self.num_pts]
            return torch.linspace(0, n - 1, self.num_pts).long()

        base = torch.arange(n, dtype=torch.long)
        if self.augment:
            extra = torch.randint(0, n, (self.num_pts - n,), dtype=torch.long)
        else:
            extra = torch.arange(self.num_pts - n, dtype=torch.long) % n
        return torch.cat([base, extra], dim=0)

    def __getitem__(self, idx: int) -> dict:
        with open(self.paths[idx], "rb") as fp:
            data = pickle.load(fp)

        tool_key = str(data["tool_key"])
        tool_scale = float(data.get("tool_scale", 1.0))
        pose_value = data["tool_pose"] if "tool_pose" in data else data["hand_pose"]
        tool_pose = torch.as_tensor(pose_value, dtype=torch.float32)

        tool_pc = self._load_tool_cloud(tool_key, tool_scale).clone()
        tool_pc = _apply_pose(tool_pc, tool_pose)

        obj_pc_full = torch.as_tensor(data["object_cloud"], dtype=torch.float32)
        contact_full = torch.as_tensor(data["contact_flag"], dtype=torch.bool)
        sample_idx = self._sample_indices(obj_pc_full.shape[0])
        obj_pc = obj_pc_full[sample_idx]
        obj_contact_flag = contact_full[sample_idx]

        if self.augment:
            tool_pc = tool_pc + torch.randn_like(tool_pc) * 1e-3
            obj_pc = obj_pc + torch.randn_like(obj_pc) * 1e-3

        return {
            "tool_pc": tool_pc.float(),
            "obj_pc": obj_pc.float(),
            "obj_contact_flag": obj_contact_flag.float(),
        }


def collect_corn_files(data_dir: str) -> List[str]:
    return sorted(str(p) for p in Path(data_dir).rglob("*.pkl"))


def make_corn_split(
    data_dir: str,
    val_ratio: float = 0.1,
    seed: int = 42,
    augment: bool = True,
    max_files: int = 0,
    tool_root: str = DEFAULT_TOOL_ROOT,
    num_pts: int = 512,
) -> Tuple[CornContactDataset, CornContactDataset]:
    files = collect_corn_files(data_dir)
    if not files:
        raise RuntimeError(f"No .pkl files found under {data_dir}")
    rng = random.Random(seed)
    rng.shuffle(files)
    if max_files > 0:
        files = files[:max_files]
    n_val = max(1, int(len(files) * val_ratio))
    val_files = files[:n_val]
    train_files = files[n_val:] or val_files
    return (
        CornContactDataset(train_files, tool_root=tool_root, num_pts=num_pts, augment=augment),
        CornContactDataset(val_files, tool_root=tool_root, num_pts=num_pts, augment=False),
    )
